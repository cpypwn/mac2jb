"""Explicit setup for this app's plaintext emulator repacks; never retail keys."""
from pathlib import Path
import argparse,datetime,hashlib,json,os,re,shutil,tempfile

PLACEHOLDERS={
    'header_key':hashlib.sha256(b'local-plaintext-xci-header-placeholder').hexdigest(),
    'key_area_key_application_00':hashlib.md5(b'local-plaintext-xci-area-placeholder').hexdigest(),
}

def placeholder_text(names=None):
    selected=PLACEHOLDERS if names is None else {k:PLACEHOLDERS[k] for k in names}
    return ('# Local placeholders for unsigned plaintext repacks; NOT Nintendo keys.\n'
            '# Cannot decrypt retail content. Keep real keys in prod.keys.\n'+
            ''.join(name+' = '+value+'\n' for name,value in selected.items()))

def inspect(directory):
    """Return names/status only. Never expose values from an existing key file."""
    directory=Path(directory);effective={}
    for filename in ('prod.keys_autogenerated','prod.keys'):
        path=directory/filename
        if path.is_symlink():raise ValueError('Choose a real emulator keys folder, without linked key files.')
        if not path.exists():continue
        if path.stat().st_size>8*1024*1024:raise ValueError('Key configuration file is unexpectedly large.')
        for line in path.read_text(encoding='utf-8-sig').splitlines():
            if line.strip().startswith('#') or '=' not in line:continue
            name,value=line.split('=',1);name=name.strip().lower()
            if name in PLACEHOLDERS:effective[name]=value.strip()
    missing=[k for k in PLACEHOLDERS if k not in effective]
    invalid=[k for k,v in effective.items() if not re.fullmatch('[0-9a-fA-F]{'+str(len(PLACEHOLDERS[k]))+'}',v)]
    return {'ready':not missing and not invalid,'missing':missing,'invalid':invalid}

def install(directory):
    """User-invoked only. Add missing placeholders, preserving all existing entries."""
    directory=Path(directory).resolve()
    directory.mkdir(parents=True,exist_ok=True)
    status=inspect(directory)
    if status['invalid']:raise ValueError('Existing entries need manual correction: '+', '.join(status['invalid']))
    if status['ready']:return {**status,'added':[],'backup':None}
    target=directory/'prod.keys_autogenerated'
    before=target.read_bytes() if target.exists() else None
    addition=placeholder_text(status['missing']).encode('utf-8')
    content=(before or b'')+(b'\n' if before and not before.endswith(b'\n') else b'')+addition
    backup=None
    if before is None:
        with target.open('xb') as f:f.write(content);f.flush();os.fsync(f.fileno())
    else:
        backup=target.with_name(target.name+'.packager-backup-'+datetime.datetime.now().strftime('%Y%m%d-%H%M%S-%f'))
        with backup.open('xb') as f:f.write(before)
        with tempfile.NamedTemporaryFile(prefix='.packager-',suffix='.tmp',dir=directory,delete=False) as f:
            temp=Path(f.name);f.write(content);f.flush();os.fsync(f.fileno())
        try:
            if target.read_bytes()!=before:raise ValueError('Key configuration changed during setup. Try again with the emulator closed.')
            os.replace(temp,target)
        finally:
            if temp.exists():temp.unlink()
    return {**inspect(directory),'added':status['missing'],'backup':str(backup) if backup else None}

if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('directory',type=Path)
    parser.add_argument('--install',action='store_true');args=parser.parse_args()
    print(json.dumps(install(args.directory) if args.install else inspect(args.directory)))
